export function getLocalizedStaticSeo(sub: string, lang: LocaleCode): LocalizedSeoEntry | null {
  // Canonicalize aliases to match primary keys
  const aliasMap: Record<string, string> = {
    "tarot/yes-no": "yes-no-tarot",
    "tarot/career": "career-tarot-reading",
    "guide/major-arcana-meanings": "major-arcana-tarot-cards-meanings",
    "guide/reversed-tarot-cards": "what-do-reversed-tarot-cards-mean",
  };
  const key = aliasMap[sub] ?? sub;
  const entry = STATIC_LOCALIZED_SEO[key];
  if (!entry) return null;
  const title = entry.title[lang] ?? entry.title.en;
  const section = entry.sectionKey ? SECTION_NAMES[entry.sectionKey][lang] : undefined;
  return {
    title,
    description: entry.description[lang] ?? entry.description.en,
    section,
    crumbTitle: title.replace(/\s*\|.*$/, ""),
  };
}

