export function getCareerUi(lang: LocaleCode): CareerUiText {
  return CAREER_UI_BY_LANG[lang] ?? CAREER_UI_DEFAULT;
}

export function buildLocalizedCareerNote(
  card: TarotCard,
  reversed: boolean,
  positionIndex: number,
  lang: LocaleCode,
): string {
  const ui = getCareerUi(lang);
  const posLabel = ui.positions[positionIndex]?.label ?? `${positionIndex + 1}`;
  if (lang === "en") {
    return `${posLabel}: ${card.name} (${reversed ? "Reversed" : "Upright"}) — ${card.careerMeaning}. ${card.financeMeaning}.`;
  }
  const locName = getLocalizedCardName(card.name, lang);
  const core = reversed ? card.reversedMeaning : card.uprightMeaning;
  return `${posLabel} — ${locName}: ${core}. ${card.careerMeaning}.`;
}

