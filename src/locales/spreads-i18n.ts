export function getLocalizedReadingLanding(
  key: TarotLandingKey,
  base: ReadingLandingConfig,
  lang: LocaleCode,
  t: (k: TranslationKey) => string,
): ReadingLandingConfig {
  if (lang === "en") return base;
  const meta = LANDING_META[key];
  const locSpread = getLocalizedSpread(getSpread(base.spreadId), t);

  // Localize positionsBreakdown when present
  let localizedBreakdown: SpreadPositionBreakdownItem[] | undefined = base.positionsBreakdown;
  if (base.positionsBreakdown) {
    if (key === "celtic-cross") {
      localizedBreakdown = base.positionsBreakdown.map((item, idx) => {
        const sp = locSpread.positions[idx];
        return {
          ...item,
          label: sp?.name ?? item.label,
          focus: sp?.meaning ?? item.focus,
          description: sp?.meaning ? `${sp.name} — ${sp.meaning}` : item.description,
        };
      });
    } else if (key === "three-card") {
      localizedBreakdown = base.positionsBreakdown.map((item, idx) => {
        const sp = locSpread.positions[idx];
        return {
          ...item,
          label: sp?.name ?? item.label,
          focus: sp?.meaning ?? item.focus,
          description: sp?.meaning ? `${sp.name}: ${sp.meaning}` : item.description,
        };
      });
    }
  }

  const localizedSections = base.sections.map((sec) => {
    const title = meta.sectionTitles[sec.id]?.[lang] ?? sec.title;
    const customParas =
      key === "celtic-cross" ? CELTIC_SECTION_COPY[sec.id]?.[lang] : undefined;
    return {
      ...sec,
      title,
      paragraphs: customParas && customParas.length > 0 ? customParas : sec.paragraphs,
    };
  });

  const localizedRelatedCards = base.relatedCards.map((rc) => ({
    ...rc,
    name: getLocalizedCardNameBySlug(rc.slug, rc.name, lang),
  }));

  const linkLabelMap: Record<string, string> = {
    "/tarot": t("tarotUi.all78Cards"),
    "/tarot/one-card": LANDING_META["one-card"].eyebrow[lang],
    "/tarot/three-card": LANDING_META["three-card"].eyebrow[lang],
    "/tarot/love": LANDING_META.love.eyebrow[lang],
    "/tarot/celtic-cross": LANDING_META["celtic-cross"].eyebrow[lang],
    "/career-tarot-reading": LANDING_META.career.eyebrow[lang],
    "/yes-no-tarot": LANDING_META["yes-no"].eyebrow[lang],
    "/numerology": t("numerology.navLabel"),
    "/guide/tarot-for-beginners": t("guideHub.g4Title"),
    "/guide/tarot-spreads": t("guideHub.g2Title"),
    "/guide/tarot-card-meanings": t("guideHub.g1Title"),
    "/guide/celtic-cross-guide": t("guideHub.g7Title"),
  };

  const localizedLinks = base.relatedLinks.map((rl) => ({
    ...rl,
    label: linkLabelMap[rl.to] ?? rl.label,
  }));

  return {
    ...base,
    eyebrow: meta.eyebrow[lang],
    h1: meta.h1[lang],
    intro: meta.intro[lang],
    ctaLabel: meta.ctaLabel[lang],
    readingTime: `${base.readingTime?.match(/\d+/)?.[0] ?? "6"} ${t("common.minRead")}`,
    positionsBreakdownEyebrow:
      key === "three-card" || key === "celtic-cross"
        ? BREAKDOWN_HEADERS[key].eyebrow[lang]
        : base.positionsBreakdownEyebrow,
    positionsBreakdownHeading:
      key === "three-card" || key === "celtic-cross"
        ? BREAKDOWN_HEADERS[key].heading[lang]
        : base.positionsBreakdownHeading,
    positionsBreakdown: localizedBreakdown,
    sections: localizedSections,
    relatedCards: localizedRelatedCards,
    relatedLinks: localizedLinks,
  };
}

