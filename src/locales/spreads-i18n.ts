export function getLocalizedYesNoExplanation(
  card: TarotCard,
  reversed: boolean,
  verdict: YesNo,
  lang: LocaleCode,
  verdictLabel: string,
): string {
  if (lang === "en") {
    const focus = reversed ? card.reversedMeaning.toLowerCase() : card.uprightMeaning.toLowerCase();
    return `${card.name} (${reversed ? "Reversed" : "Upright"}) → ${verdictLabel}: ${focus}.`;
  }
  const locName = getLocalizedCardName(card.name, lang);
  const baseMeaning = reversed ? card.reversedMeaning : card.uprightMeaning;
  return `${locName} — ${verdictLabel}: ${baseMeaning}.`;
}

