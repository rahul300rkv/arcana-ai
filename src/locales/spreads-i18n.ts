export function getThreeCardUi(lang: LocaleCode): ThreeCardUiText {
  return THREE_CARD_UI_BY_LANG[lang] ?? THREE_CARD_UI_DEFAULT;
}

export function buildLocalizedThreeCardNote(
  card: TarotCard,
  reversed: boolean,
  framing: "timeline" | "troubleshoot" | "wellness",
  index: number,
  lang: LocaleCode,
): string {
  const ui = getThreeCardUi(lang);
  const posName = ui.positions[framing][index]?.label ?? `${index + 1}`;
  const locName = getLocalizedCardName(card.name, lang);
  if (lang === "en") {
    const uprightSummary = card.uprightMeaning.toLowerCase();
    const reversedSummary = card.reversedMeaning.toLowerCase();
    if (!reversed) {
      return `${posName}: ${card.name} upright highlights ${uprightSummary}. Focus on ${card.spiritualityMeaning.toLowerCase()}.`;
    }
    return `${posName}: ${card.name} reversed signals quiet recalibration around ${reversedSummary}.`;
  }
  const summary = reversed ? card.reversedMeaning : card.uprightMeaning;
  return `${posName} — ${locName} (${reversed ? "Reversed" : "Upright"}): ${summary}. ${card.spiritualityMeaning}.`;
}

