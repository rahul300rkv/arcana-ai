export type TranslationKey = keyof typeof strings;

/**
 * Looks up a translation. Falls back to English when a given language
 * doesn't have this key translated yet (currently: the long-form Privacy
 * Policy / Terms of Service copy in languages other than en/hi/hinglish).
 */
export function t(key: TranslationKey, lang: Language): string {
  const entry = strings[key] as Dict;
  return entry[lang] ?? entry.en;
}

export function useTranslate() {
  const [lang] = useLanguage();
  // Memoized against `lang` so components calling `const t = useTranslate()`
  // get a stable function reference across re-renders that don't change the
  // language — letting them pass `t` to memoized children (e.g. React.memo
  // components) without defeating that memoization every render.
  return useCallback((key: TranslationKey) => t(key, lang), [lang]);
}
